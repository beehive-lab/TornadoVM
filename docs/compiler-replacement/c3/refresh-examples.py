#!/usr/bin/env python3
"""Refresh the generated stages in examples.md from the dumps in c3/from-java/.

Each `## <kernel>` section has `### <stage>` headings followed by one fenced block; this replaces
the block's body with the matching dump file, so examples.md never holds hand-edited compiler output.
Usage: refresh-examples.py   (after DesignTest --java has written the dumps into c3/from-java/)
"""
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DOC = HERE.parent / "examples.md"
SECTIONS = {
    "Grid-stride vector addition": "vector-add",
    "If/else with `sqrt`": "branchy",
    "KernelContext shared-memory tree reduction": "block-reduce",
    "`@Parallel` 1D vector addition": "parallel-add",
    "`@Parallel` 2D matrix addition": "parallel-matrix",
}
STAGES = [
    ("Bytecode", ".bytecode.txt"),
    ("TC-SSA from the frontend", ".pre-abi.tcir"),
    ("TC-SSA after ABI lowering", ".post-abi.tcir"),
    ("TC-S", ".tcs"),
    ("CUDA generated by TC", ".cu"),
]


def main():
    lines = DOC.read_text().splitlines()
    out, prefix, stage_file, i = [], None, None, 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("## "):
            prefix = SECTIONS.get(line[3:].strip())
        elif line.startswith("### ") and prefix:
            stage_file = next((HERE / "from-java" / (prefix + suffix) for title, suffix in STAGES if line[4:].startswith(title)), None)
        elif line.startswith("```") and len(line) > 3 and stage_file is not None:
            out.append(line)
            i += 1
            while not lines[i].startswith("```"):
                i += 1
            out.extend(stage_file.read_text().rstrip("\n").splitlines())
            out.append(lines[i])
            stage_file = None
            i += 1
            continue
        out.append(line)
        i += 1
    DOC.write_text("\n".join(out) + "\n")

if __name__ == "__main__":
    main()
