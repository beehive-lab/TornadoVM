#!/usr/bin/env python3
"""Regenerate the CHECK lines of TC lit tests from the current tool output.

The TC analogue of LLVM's update_test_checks.py: for every given test file, run the first RUN line's
tool on it, drop the existing autogenerated CHECK block, and write a CHECK-LABEL per function plus
CHECK-NEXT lines for its body. Review the diff by hand: the output becomes the expected result.

Usage: update-checks.py <test.tcir>...   (build first: ./mvnw -o -Pjdk21 -pl tornado-compiler/<module> -am install -DskipTests)
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOLS = {
    "tc-ir": ("uk.ac.manchester.tornado.tc.ir.tools.IrTool", ["tc-ir"]),
    "tc-lower": ("uk.ac.manchester.tornado.tc.lower.tools.LowerTool", ["tc-ir", "tc-lower"]),
    "tc-opt": ("uk.ac.manchester.tornado.tc.opt.tools.OptTool", ["tc-ir", "tc-opt"]),
    "tc-emit": ("uk.ac.manchester.tornado.tc.codegen.tools.EmitTool", ["tc-ir", "tc-lower", "tc-codegen"]),
    "tc-tornado": ("uk.ac.manchester.tornado.tc.tornado.tools.TornadoTool", ["tc-ir", "tc-tornado"]),
    "tc-java": ("uk.ac.manchester.tornado.tc.frontend.tools.JavaTool", ["tc-ir", "tc-frontend"]),
}
MARK_BEGIN = "; ---- autogenerated by utils/update-checks.py; edit with care ----"
MARK_END = "; ---- end of autogenerated checks ----"


def run_line(text):
    for line in text.splitlines():
        m = re.match(r"\s*;\s*RUN:\s*(.*)$", line)
        if m and "FileCheck" in m.group(1):
            return m.group(1)
    raise SystemExit("no RUN line with FileCheck")


def tool_output(test, run):
    first = run.split("|")[0].split()
    name, args = first[0], [a.replace("%s", str(test)) for a in first[1:]]
    main, modules = TOOLS[name]
    cp = ":".join(str(ROOT / m / "target" / "classes") for m in modules)
    module_dir = next(p for p in test.parents if (p / "pom.xml").exists())  # RUN lines are relative to the module
    result = subprocess.run(["java", "-cp", cp, main, *args], capture_output=True, text=True, stdin=subprocess.DEVNULL, cwd=module_dir)
    if result.returncode != 0:
        raise SystemExit(f"{test}: tool failed:\n{result.stderr}")
    return result.stdout


def checks(output, prefix="CHECK"):
    lines = []
    new_function = True
    for line in output.splitlines():
        if not line.strip():
            new_function = True
            continue
        if new_function or re.match(r"^(kernel|device)\b", line) or line.startswith('extern "C"'):
            lines.append(f"; {prefix}-LABEL: {line}")
            new_function = False
        else:
            lines.append(f"; {prefix}-NEXT:  {line}")
    return lines


def main():
    for arg in sys.argv[1:]:
        test = pathlib.Path(arg).resolve()
        text = test.read_text()
        if MARK_BEGIN in text:
            text = text[: text.index(MARK_BEGIN)] + text[text.index(MARK_END) + len(MARK_END) + 1:]
        run = run_line(text)
        block = [MARK_BEGIN, *checks(tool_output(test, run)), MARK_END]
        lines = text.splitlines()
        insert = max(i for i, l in enumerate(lines) if re.match(r"\s*;\s*RUN:", l)) + 1
        lines[insert:insert] = block
        test.write_text("\n".join(lines) + "\n")
        print(f"updated {arg}: {len(block) - 2} check lines")


if __name__ == "__main__":
    main()
